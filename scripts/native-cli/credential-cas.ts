import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve,join} from 'node:path';
import {CredentialHelperClient,createSubprocessCredentialTransport} from '../../packages/credential-helper/src/index.ts';
import {createLlmConfigStore} from '../../apps/desktop/electron/main/llm-config-store.mjs';
import {DEFAULT_SUBSCRIPTION_MODEL} from '../../apps/desktop/electron/main/provider-adapters/openai-model-catalog.mjs';
const home=mkdtempSync(join(tmpdir(),'peer-helper-cas-'));
try {
 writeFileSync(join(home,'.native-cli-fixture'),'isolated');writeFileSync(join(home,'.synthetic-vault-key'),Buffer.alloc(32,17),{mode:0o600});
 const client=new CredentialHelperClient(createSubprocessCredentialTransport({explicitPath:resolve('target/debug/examples/vault-fixture'),dataHome:home}));
 assert.equal(client.supportsModelOAuthCas(),true);
 const key='model/fixture/oauth-tokens';
 assert.deepEqual(client.getSnapshot(key),{secret:null,revision:null});
 assert.equal(client.compareSet(key,null,'synthetic-first'),true);
 const first=client.getSnapshot(key);assert.equal(first.secret,'synthetic-first');assert.match(first.revision!,/^[A-Za-z0-9+/]{16}$/);
 assert.equal(client.compareSet(key,null,'cannot-create-twice'),false);
 client.setSecret(key,'new-login');
 const before=readFileSync(join(home,'credentials.vault.json'));
 assert.equal(client.compareSet(key,first.revision,'late-refresh'),false);assert.deepEqual(readFileSync(join(home,'credentials.vault.json')),before);
 assert.equal(client.getSecret(key),'new-login');
 const second=client.getSnapshot(key);assert.notEqual(second.revision,first.revision);
 client.deleteSecret(key);assert.equal(client.compareSet(key,second.revision,'resurrection'),false);assert.equal(client.getSecret(key),null);
 assert.equal(client.compareSet(key,null,'replacement'),true);
 const third=client.getSnapshot(key);assert.equal(client.compareSet(key,third.revision,null),true);assert.equal(client.getSecret(key),null);
 assert.throws(()=>client.getSnapshot('model/fixture/api-key'));
 assert.throws(()=>client.compareSet(key,'invalid','value'));
 const store=createLlmConfigStore({configFile:join(home,'llm-providers.json'),credentialClient:client});
 const model=store.addProvider({provider:'openai',channelId:'openai',authMethod:'oauth_chatgpt',groupId:'fixture',model:DEFAULT_SUBSCRIPTION_MODEL});
 const pending={access:'old',refresh:'old-refresh',expires:1,peerModelRefresh:{schemaVersion:1,attemptId:'11111111-1111-4111-8111-111111111111',authMethod:'oauth_chatgpt',phase:'in_flight',createdAt:1}};
 client.setSecret(key,JSON.stringify(pending));
 assert.throws(()=>client.getSecret(key),(e:any)=>e.code==='credential_oauth_refresh_pending');
 assert.deepEqual(JSON.parse(client.getSnapshot(key).secret!),pending);
 const newLogin={access:'new-login',refresh:'new-login-refresh',expires:Date.now()+3600000,accountId:'account'};
 assert.throws(()=>store.setOAuthTokens(model.id,newLogin),/credential_oauth_refresh_pending/);
 assert.deepEqual(JSON.parse(client.getSnapshot(key).secret!),pending);
 store.setOAuthTokens(model.id,newLogin,{allowPending:true});
 assert.deepEqual(JSON.parse(client.getSecret(key)!),newLogin);
 console.log('Actual TS client -> encrypted Rust Vault snapshot/CAS/legacy rotation/logout roundtrip passed.');
}finally{rmSync(home,{recursive:true,force:true});}
