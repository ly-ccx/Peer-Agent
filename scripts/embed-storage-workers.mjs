import { transpileModule, ModuleKind, ScriptTarget } from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

// A self-contained worker source also survives Bun's single-file CLI compiler.
// Keep reducer implementations canonical; never maintain a second reducer here.
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sqliteSource = readFileSync(path.join(root, 'packages/runtime-node/src/sqlite/connection.mjs'), 'utf8');
writeFileSync(path.join(root, 'packages/conversation-store/src/sqlite-runtime.generated.mjs'),
  '// Generated from runtime-node/sqlite/connection.mjs. Do not edit.\n' + sqliteSource);
const builtins = includeLstat => `const {createHash,randomUUID}=require('node:crypto');
const {createRequire}=require('node:module');
const {Worker,isMainThread,parentPort,workerData}=require('node:worker_threads');
const {copyFile,truncate,open:legacyOpen}=require('node:fs/promises');
const {realpathSync,linkSync,unlinkSync,writeFileSync,mkdirSync,readFileSync,renameSync,existsSync,statSync,${includeLstat ? 'lstatSync,' : ''}openSync,closeSync,fsyncSync,writeSync,fstatSync,readSync,readdirSync}=require('node:fs');
const path=require('node:path');\n`;
const resourceHintSource = transpileModule(readFileSync(path.join(root, 'packages/protocol/src/resource-reference-hints.ts'), 'utf8'),
  { compilerOptions: { module: ModuleKind.ESNext, target: ScriptTarget.ES2022 } }).outputText;
const targets = [
  { output: 'packages/runtime-node/src/project-agent/coordination-worker-source.generated.mjs', name: 'COORDINATION_WORKER_SOURCE', files: ['packages/runtime-node/src/project-agent/history-resumption.mjs', 'packages/runtime-node/src/project-agent/coordination-kernel.mjs', 'packages/runtime-node/src/project-agent/work-delta.mjs', 'packages/runtime-node/src/project-agent/work-coordination.mjs', 'packages/runtime-node/src/project-agent/journal-lines.mjs', 'packages/runtime-node/src/project-agent/coordination-legacy-integrity.mjs', 'packages/runtime-node/src/project-agent/coordination-storage-v2.mjs'] },
  { output: 'packages/conversation-store/src/interaction-worker-source.generated.mjs', name: 'INTERACTION_WORKER_SOURCE', files: ['packages/conversation-store/src/interaction-reader.mjs'] },
];
for (const target of targets) {
  const source = builtins(target.name === 'COORDINATION_WORKER_SOURCE') + [sqliteSource, ...(target.name === 'INTERACTION_WORKER_SOURCE' ? [resourceHintSource] : []), ...target.files.map(file => readFileSync(path.join(root, file), 'utf8'))].map(source => source
    .replace(/^import .*?;\n/gm, '').replace(/^export /gm, '')
    .replaceAll('import.meta.url', "'file:///embedded-storage-worker.mjs'")).join('\n');
  writeFileSync(path.join(root, target.output), `// Generated by scripts/embed-storage-workers.mjs. Do not edit.\nexport const ${target.name} = ${JSON.stringify(source)};\n`);
}
