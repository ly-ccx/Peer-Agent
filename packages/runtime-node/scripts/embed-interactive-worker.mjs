import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Bundle the canonical public SDK adapter once. A compiled CLI must not try to
// import a source worker or npm dependencies from the user's working directory.
const entry = new URL('../src/interactive-results/validation-worker.mjs', import.meta.url);
const result = await build({ entryPoints: [fileURLToPath(entry)], bundle: true, write: false,
  platform: 'node', format: 'cjs', target: 'node22', external: ['node:*'], minify: true, legalComments: 'inline',
  define: { 'process.env.NODE_ENV': '"production"', 'process.env.OPENUI_TELEMETRY_DISABLED': '"1"', 'process.env.OPENUI_RUNTIME_TELEMETRY_ENABLED': '"0"' } });
const source = result.outputFiles[0].text;
if (Buffer.byteLength(source) > 2 * 1024 * 1024) throw Error('Interactive worker bundle exceeds its admitted size.');
await writeFile(new URL('../src/interactive-results/validation-worker-source.generated.mjs', import.meta.url),
  `// Generated by scripts/embed-interactive-worker.mjs from the canonical adapter and fixed SDK. Do not edit.\nexport const INTERACTIVE_VALIDATION_WORKER_SOURCE = ${JSON.stringify(source)};\n`);
