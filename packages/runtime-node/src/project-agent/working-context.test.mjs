import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { createWorkCoordinationStore } from './work-coordination-store.mjs';
import { registerWorkBudget } from './work-budget.mjs';
import { createWorkingContext, readWorkingContext } from './working-context.mjs';

test('notes and prepared handoff retain work identity and usage; scoped history is paged', async t => {
  const rootDir = mkdtempSync(path.join(os.tmpdir(), 'peer-working-context-'));
  const store = createWorkCoordinationStore({ rootDir, workspaceId: 'w', holdsLease: () => true, leaseEpoch: () => 'owner', formatVersion: 2, fenceLegacyWrites: true });
  await store.prepare();
  store.saveWork({ workId: 'work', parentConversationId: 'parent', state: 'runnable', budget: { modelRequests: 9, tokens: 45 } });
  store.saveWork({ workId: 'other', parentConversationId: 'unrelated', state: 'runnable' });
  const release = registerWorkBudget('w', store);
  t.after(() => { release(); store.close(); rmSync(rootDir, { recursive: true, force: true }); });
  let historyInput;
  const context = createWorkingContext({ supervisor: { readWorkHistory(input) { historyInput = input; return { conversationId: 'parent', sourceVersion: 'v1', messages: [{ id: 'm1', kind: 'user_input', content: 'The original target' }], nextCursor: 'older' }; } } });
  const view = { role: 'project_agent', workspaceId: 'w', workId: 'work', conversationId: 'parent' };
  const note = await context.execute('write_work_note', { name: 'Next step', text: 'Read evidence before accepting.', expectedRevision: 0, sourceRefs: ['m1'] }, view, 'write-one');
  assert.equal(note.note.revision, 1);
  assert.equal((await context.execute('write_work_note', { name: 'Next step', text: 'Read evidence before accepting.', expectedRevision: 0, sourceRefs: ['m1'] }, view, 'write-one')).replayed, true);
  await assert.rejects(context.execute('write_work_note', { name: 'Next step', text: 'Clobber', expectedRevision: 0 }, view, 'write-two'), /conflict/);
  await assert.rejects(context.execute('read_work_notes', { workId: 'other' }, view, 'read-other'), /out_of_scope/);
  const window = await context.execute('prepare_context_handoff', { hint: 'Still waiting for evidence.' }, view, 'handoff-one');
  assert.equal(window.providerWindowChanged, false);
  assert.equal(window.window.budgetRef, 'work');
  assert.equal(window.window.state, 'prepared');
  assert.equal(store.readWork('work').budget.tokens, 45);
  const admitted = readWorkingContext({ workspaceId: 'w', workId: 'work', conversationId: 'parent' });
  assert.equal(admitted.notes[0].noteId, note.note.noteId);
  assert.equal(admitted.windowId, window.window.windowId);
  store.saveWork({ workId: 'work-B', parentConversationId: 'parent', state: 'runnable' });
  const viewB = { ...view, workId: 'work-B' };
  for (let index = 0; index < 9; index++) await context.execute('write_work_note', { name: `Other ${index}`, text: 'Another task', expectedRevision: 0 }, viewB, `other-${index}`);
  await context.execute('prepare_context_handoff', { hint: 'Another task context' }, viewB, 'other-window');
  const retained = readWorkingContext({ workspaceId: 'w', workId: 'work', conversationId: 'parent' });
  assert.equal(retained.notes[0].noteId, note.note.noteId);
  assert.equal(retained.windowId, window.window.windowId);
  const history = await context.execute('search_work_history', { before: 'cursor', limit: 5, query: 'original' }, view, 'history');
  assert.equal(historyInput.before, 'cursor');
  assert.equal(history.matches[0].messageId, 'm1');
  assert.equal(history.nextCursor, 'older');
  store.saveWork({ ...store.readWork('work'), state: 'paused' });
  await assert.rejects(context.execute('prepare_context_handoff', { hint: 'Must not restart' }, view, 'handoff-two'), /work_execution_stopped/);
});
